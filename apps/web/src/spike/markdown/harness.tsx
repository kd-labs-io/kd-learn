// SPIKE (phase 1 step 6): streams a fixture into a renderer chunk by chunk, in the browser, and
// measures layout stability, raw-syntax leaks, display lag, frame pacing and injected-markup
// behaviour. Driven by apps/web/scripts/spike-markdown.mjs through window.__mdSpike.
//
// Sampling is per animation frame, not per chunk: Astryx's streaming mode reveals text on
// requestAnimationFrame (useStreamingText), so what the reader sees only changes on frames.
import { lazy, Suspense, useEffect, useRef, useState } from 'react';
import { flushSync } from 'react-dom';
import { chunkText, HOSTILE, TEACHER_ANSWER } from './fixture';
import { stabilize } from './stabilize';

// Each candidate is its own chunk so the build reports per-candidate size.
const TanstackLazy = lazy(() =>
  import('./tanstack').then((m) => ({ default: m.TanstackMarkdown })),
);
const AstryxLazy = lazy(() => import('./astryx').then((m) => ({ default: m.AstryxMarkdown })));

export type RendererId = 'tanstack' | 'astryx';
export type FixtureId = 'teacher' | 'hostile';

export interface RunOptions {
  renderer: RendererId;
  fixture: FixtureId;
  /** Hold back unfinished syntax with ./stabilize before it reaches the renderer. */
  stabilize: boolean;
  /** Delay before each chunk. */
  intervalMs: number;
  /** Repeat the fixture to test cost growth on a long answer. */
  repeat?: number;
  seed?: number;
  /** Only feed chunks (no sampling), for whole-run CPU totals taken outside the page. */
  lean?: boolean;
  /** Stop (without ending the stream) once the text so far contains this marker, for screenshots. */
  stopAtMarker?: string;
}

const FIXTURES: Record<FixtureId, string> = { teacher: TEACHER_ANSWER, hostile: HOSTILE };
const STRUCTURAL = 'pre, table, ul, ol, blockquote, h2, h3, [data-math-block]';
/** Currency in the fixture ("giá $5 hoặc $10") is literal text, also while it is half received. */
const CURRENCY = /giá \$\d*(?: hoặc \$\d*)?/g;
const sleep = (ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms));
const frame = () => new Promise<number>((resolve) => requestAnimationFrame((t) => resolve(t)));

const stats = (values: number[]) => {
  const sorted = [...values].sort((a, b) => a - b);
  const at = (q: number) => sorted[Math.min(sorted.length - 1, Math.floor(q * sorted.length))] ?? 0;
  const sum = values.reduce((a, b) => a + b, 0);
  return {
    n: values.length,
    mean: sum / Math.max(1, values.length),
    p50: at(0.5),
    p95: at(0.95),
    max: sorted.at(-1) ?? 0,
    total: sum,
  };
};

/** Text a reader sees: skips code, math output, placeholders and tables. */
function visibleText(root: Element): string {
  const skip = 'pre, code, .katex, [data-pending], style, script, table';
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let out = '';
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const parent = node.parentElement;
    if (parent && !parent.closest(skip)) out += node.textContent ?? '';
  }
  return out.replace(CURRENCY, '');
}

const DANGEROUS_TAGS = new Set([
  'SCRIPT',
  'IFRAME',
  'OBJECT',
  'EMBED',
  'SVG',
  'STYLE',
  'LINK',
  'META',
  'BASE',
  'FORM',
  'INPUT',
  'BUTTON',
  'VIDEO',
  'AUDIO',
]);

/** Anything in `root` that could run or load something the model controls. */
function findViolations(root: Element): string[] {
  const found: string[] = [];
  const all = [root, ...Array.from(root.querySelectorAll('*'))];
  for (const el of all) {
    // KaTeX's <svg> (stretchy delimiters, sqrt) and Astryx's code block chrome (copy button and
    // icon) are generated by the libraries, not by model markup.
    const own = el.closest('.katex, [class*="codeblock"]');
    if (DANGEROUS_TAGS.has(el.tagName.toUpperCase()) && !own)
      found.push(`<${el.tagName.toLowerCase()}>`);
    for (const attr of Array.from(el.attributes)) {
      const name = attr.name.toLowerCase();
      if (/^on/.test(name)) found.push(`${el.tagName.toLowerCase()}[${name}]`);
      if (['href', 'src', 'srcdoc', 'action', 'formaction', 'xlink:href'].includes(name)) {
        const value = attr.value.replace(/\s+/g, '').toLowerCase();
        if (/^(javascript|data|vbscript):/.test(value) || name === 'srcdoc') {
          found.push(`${el.tagName.toLowerCase()}[${name}=${attr.value.slice(0, 40)}]`);
        }
      }
    }
  }
  return found;
}

/** First place where two strings differ, with a little context. */
function firstDiff(a: string, b: string) {
  if (a === b) return null;
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i++;
  return {
    at: i,
    streamed: a.slice(Math.max(0, i - 60), i + 100),
    reference: b.slice(Math.max(0, i - 60), i + 100),
  };
}

export interface RunResult {
  options: RunOptions;
  chunks: number;
  chars: number;
  /** Frame intervals (ms) while streaming: jank shows as large p95/max. */
  frameMs: ReturnType<typeof stats>;
  framesOver33: number;
  /** ms spent inside flushSync per chunk (the synchronous part only; Astryx defers the rest to rAF). */
  syncRenderMs: ReturnType<typeof stats>;
  /** Shrinking content height between frames (px) = collapse. */
  shrinkEvents: number;
  maxShrinkPx: number;
  shrinkAt: { frame: number; delta: number; tail: string }[];
  maxGrowthPx: number;
  growthOver80Px: number;
  /** Completed KaTeX nodes re-created later (flash risk); structural blocks re-created while not last. */
  katexRemounts: number;
  blockRemounts: number;
  /** Frames showing raw syntax to the reader, per character class, with one sample each. */
  leakFrames: Record<string, number>;
  leakSamples: Record<string, string>;
  framesSampled: number;
  katexErrorFrames: number;
  pendingFrames: number;
  /** Display lag: the largest gap between received and displayed share of the text, and the share
   * still missing when the last chunk arrived. */
  maxLagFraction: number;
  lagAtLastChunkFraction: number;
  settleMsAfterLastChunk: number;
  /** The `streaming: false` flip: what changes at once when the stream ends. */
  snap: { charsBefore: number; charsAfter: number; heightBefore: number; heightAfter: number };
  finalKatex: number;
  finalTables: number;
  finalPre: number;
  finalHeight: number;
  convergedText: boolean;
  convergedHtml: boolean;
  /** Same comparison with class, style, id and data-* attributes removed. */
  convergedStructure: boolean;
  structureDiff: ReturnType<typeof firstDiff>;
  violations: string[];
  pwned: string | null;
  finalHtml: string;
}

declare global {
  interface Window {
    __mdSpike?: { run: (options: RunOptions) => Promise<RunResult>; ready: boolean };
    __pwned?: unknown;
  }
}

interface ViewState {
  renderer: RendererId;
  text: string;
  streaming: boolean;
  stabilize: boolean;
}

function View({ state }: { state: ViewState }) {
  const shown = state.streaming && state.stabilize ? stabilize(state.text) : state.text;
  const Renderer = state.renderer === 'astryx' ? AstryxLazy : TanstackLazy;
  return (
    <Suspense fallback={null}>
      <Renderer text={shown} streaming={state.streaming} />
    </Suspense>
  );
}

const stripAttrs = (html: string) =>
  html.replace(/\s(?:style|class|id|dir)="[^"]*"/g, '').replace(/\sdata-[a-z-]+="[^"]*"/g, '');

export function MarkdownSpike({
  initial,
}: {
  /** Static mode: render this fixture in the very first render (SSR + hydration check). */
  initial?: { renderer: RendererId; fixture: FixtureId } | undefined;
}) {
  const [state, setState] = useState<ViewState>({
    renderer: initial?.renderer ?? 'tanstack',
    text: initial ? FIXTURES[initial.fixture] : '',
    streaming: false,
    stabilize: false,
  });
  const [reference, setReference] = useState<{ renderer: RendererId; text: string } | null>(null);
  const streamRef = useRef<HTMLDivElement>(null);
  const referenceRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const textLength = () => streamRef.current?.textContent?.length ?? 0;
    const settle = async (maxMs: number) => {
      const start = performance.now();
      let last = -1;
      let stable = 0;
      while (stable < 6 && performance.now() - start < maxMs) {
        await frame();
        const now = textLength();
        stable = now === last ? stable + 1 : 0;
        last = now;
      }
    };

    const run = async (options: RunOptions): Promise<RunResult> => {
      await Promise.all([import('./tanstack'), import('./astryx')]);
      const full = FIXTURES[options.fixture].repeat(options.repeat ?? 1);
      const chunks = chunkText(full, options.seed ?? 1);
      const el = streamRef.current!;
      window.__pwned = undefined;
      flushSync(() => {
        setReference(null);
        setState({
          renderer: options.renderer,
          text: '',
          streaming: true,
          stabilize: options.stabilize,
        });
      });
      await settle(2000);

      const violations = new Set<string>();
      const leakFrames: Record<string, number> = {
        dollar: 0,
        backslash: 0,
        asterisk: 0,
        pipe: 0,
        backtick: 0,
      };
      const leakSamples: Record<string, string> = {};
      const shrinkAt: RunResult['shrinkAt'] = [];
      const frameIntervals: number[] = [];
      const series: { received: number; shown: number }[] = [];
      let shrinkEvents = 0;
      let maxShrinkPx = 0;
      let maxGrowthPx = 0;
      let growthOver80Px = 0;
      let katexRemounts = 0;
      let blockRemounts = 0;
      let katexErrorFrames = 0;
      let pendingFrames = 0;
      let framesSampled = 0;
      let received = 0;
      let running = true;
      let lastTs = 0;
      let prevHeight = el.offsetHeight;
      let prevKatex = new Set<Element>();
      let prevBlocks: Element[] = [];

      const observer = new MutationObserver((records) => {
        for (const record of records) {
          for (const node of Array.from(record.addedNodes))
            if (node instanceof Element) for (const v of findViolations(node)) violations.add(v);
          if (record.type === 'attributes' && record.target instanceof Element)
            for (const v of findViolations(record.target)) violations.add(v);
        }
      });
      if (!options.lean) observer.observe(el, { childList: true, subtree: true, attributes: true });

      const sample = (ts: number) => {
        if (lastTs) frameIntervals.push(ts - lastTs);
        lastTs = ts;
        if (!options.lean) {
          framesSampled++;
          const height = el.offsetHeight;
          const delta = height - prevHeight;
          if (delta < -1) {
            shrinkEvents++;
            maxShrinkPx = Math.max(maxShrinkPx, -delta);
            shrinkAt.push({ frame: framesSampled, delta, tail: (el.textContent ?? '').slice(-50) });
          }
          if (delta > 0) maxGrowthPx = Math.max(maxGrowthPx, delta);
          if (delta > 80) growthOver80Px++;
          prevHeight = height;
          for (const node of prevKatex) if (!node.isConnected) katexRemounts++;
          const prevLast = prevBlocks.at(-1);
          for (const node of prevBlocks)
            if (node !== prevLast && !node.isConnected) blockRemounts++;
          prevKatex = new Set(Array.from(el.querySelectorAll('.katex')));
          prevBlocks = Array.from(el.querySelectorAll(STRUCTURAL));
          const text = visibleText(el);
          const leak = (name: string, ch: string) => {
            const at = text.indexOf(ch);
            if (at === -1) return;
            leakFrames[name]!++;
            leakSamples[name] ??= text.slice(Math.max(0, at - 25), at + 25);
          };
          leak('dollar', '$');
          leak('backslash', '\\');
          leak('asterisk', '*');
          leak('pipe', '|');
          leak('backtick', '`');
          if (el.querySelector('.katex-error')) katexErrorFrames++;
          if (el.querySelector('[data-pending]')) pendingFrames++;
          series.push({ received, shown: textLength() });
        }
        if (running) requestAnimationFrame(sample);
      };
      requestAnimationFrame(sample);

      const syncMs: number[] = [];
      let acc = '';
      for (const chunk of chunks) {
        if (options.intervalMs > 0) await sleep(options.intervalMs);
        acc += chunk;
        received = acc.length;
        const t0 = performance.now();
        flushSync(() => setState((s) => ({ ...s, text: acc })));
        syncMs.push(performance.now() - t0);
        if (options.stopAtMarker && acc.includes(options.stopAtMarker)) break;
      }

      const stopped = Boolean(options.stopAtMarker && acc.length < full.length);
      const lastChunkAt = performance.now();
      const lagAtLastChunkChars = textLength();
      await settle(4000);
      const settleMsAfterLastChunk = performance.now() - lastChunkAt - 6 * 16;
      const charsBefore = textLength();
      const heightBefore = el.offsetHeight;
      if (!stopped) {
        flushSync(() => setState((s) => ({ ...s, streaming: false })));
        await frame();
        await frame();
      }
      const charsAfter = textLength();
      const heightAfter = el.offsetHeight;
      running = false;
      await sleep(300); // let async image errors and animations settle
      observer.disconnect();
      if (options.lean) {
        return {
          options,
          chunks: chunks.length,
          chars: full.length,
          frameMs: stats(frameIntervals),
          framesOver33: frameIntervals.filter((x) => x > 33.5).length,
          syncRenderMs: stats(syncMs),
        } as unknown as RunResult;
      }
      for (const v of findViolations(el)) violations.add(v);

      // One-shot reference render of the whole text with the same renderer, not streaming.
      flushSync(() => setReference({ renderer: options.renderer, text: full }));
      await settle(2000);
      const ref = referenceRef.current!;
      const finalHtml = el.innerHTML;
      const structA = stripAttrs(finalHtml);
      const structB = stripAttrs(ref.innerHTML);

      // Lag: finalShown is what the DOM shows once the stream has ended and settled.
      const finalShown = Math.max(1, charsAfter);
      let maxLagFraction = 0;
      for (const s of series)
        maxLagFraction = Math.max(
          maxLagFraction,
          s.received / full.length - Math.min(1, s.shown / finalShown),
        );

      return {
        options,
        chunks: chunks.length,
        chars: full.length,
        frameMs: stats(frameIntervals),
        framesOver33: frameIntervals.filter((x) => x > 33.5).length,
        syncRenderMs: stats(syncMs),
        shrinkEvents,
        maxShrinkPx,
        shrinkAt: shrinkAt.slice(0, 6),
        maxGrowthPx,
        growthOver80Px,
        katexRemounts,
        blockRemounts,
        leakFrames,
        leakSamples,
        framesSampled,
        katexErrorFrames,
        pendingFrames,
        maxLagFraction,
        lagAtLastChunkFraction: 1 - Math.min(1, lagAtLastChunkChars / finalShown),
        settleMsAfterLastChunk,
        snap: { charsBefore, charsAfter, heightBefore, heightAfter },
        finalKatex: el.querySelectorAll('.katex').length,
        finalTables: el.querySelectorAll('table').length,
        finalPre: el.querySelectorAll('pre').length,
        finalHeight: el.offsetHeight,
        convergedText: (el.textContent ?? '') === (ref.textContent ?? ''),
        convergedHtml: finalHtml === ref.innerHTML,
        convergedStructure: structA === structB,
        structureDiff: firstDiff(structA, structB),
        violations: Array.from(violations),
        pwned: window.__pwned === undefined ? null : String(window.__pwned),
        finalHtml,
      };
    };

    window.__mdSpike = { ready: true, run };
    return () => {
      delete window.__mdSpike;
    };
  }, []);

  return (
    <div>
      <div id="spike-stream" ref={streamRef}>
        <View state={state} />
      </div>
      {reference ? (
        <div id="spike-reference" ref={referenceRef} hidden>
          <View
            state={{
              renderer: reference.renderer,
              text: reference.text,
              streaming: false,
              stabilize: false,
            }}
          />
        </div>
      ) : null}
    </div>
  );
}
